CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE, description VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id INTEGER NOT NULL REFERENCES roles(id), full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE, phone VARCHAR(20) UNIQUE,
    password_hash VARCHAR(255) NOT NULL, address TEXT, is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP, updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS carts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE REFERENCES users(id), updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS brands (id INTEGER PRIMARY KEY, name VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS categories (id INTEGER PRIMARY KEY, name VARCHAR(100), slug VARCHAR(100));
CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY, brand_id INTEGER REFERENCES brands(id), category_id INTEGER REFERENCES categories(id),
    name VARCHAR(255), status VARCHAR(30), description TEXT, warranty_period_months INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS product_variants (
    id INTEGER PRIMARY KEY, product_id INTEGER REFERENCES products(id), serial_code VARCHAR(100),
    variant_name VARCHAR(255), price NUMERIC(18,2), original_price NUMERIC(18,2),
    stock_quantity INTEGER, image_url VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS cart_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id INTEGER NOT NULL REFERENCES carts(id), product_variant_id INTEGER NOT NULL REFERENCES product_variants(id),
    quantity INTEGER NOT NULL, created_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS specifications (id INTEGER PRIMARY KEY, name VARCHAR(100));
CREATE TABLE IF NOT EXISTS specification_options (id INTEGER PRIMARY KEY, display_value VARCHAR(255));
CREATE TABLE IF NOT EXISTS specification_values (
    id INTEGER PRIMARY KEY, product_variant_id INTEGER REFERENCES product_variants(id),
    specification_id INTEGER REFERENCES specifications(id), option_id INTEGER REFERENCES specification_options(id), value TEXT
);
CREATE TABLE IF NOT EXISTS category_specifications (
    category_id INTEGER REFERENCES categories(id), specification_id INTEGER REFERENCES specifications(id),
    is_primary BOOLEAN, is_filterable BOOLEAN
);
CREATE TABLE IF NOT EXISTS promotions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(50) UNIQUE, name VARCHAR(150), discount_type VARCHAR(50),
    discount_value NUMERIC(18,2), usage_limit INTEGER, is_active BOOLEAN,
    start_date TIMESTAMP, end_date TIMESTAMP
);
CREATE TABLE IF NOT EXISTS banners (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, promotion_id INTEGER REFERENCES promotions(id),
    title VARCHAR(150), image_url VARCHAR(255) NOT NULL, link_url VARCHAR(255), display_order INTEGER DEFAULT 0, is_active BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id), order_code VARCHAR(50) NOT NULL UNIQUE,
    total_amount NUMERIC(12,2) NOT NULL, discount_amount NUMERIC(12,2) DEFAULT 0,
    final_amount NUMERIC(12,2) NOT NULL, status VARCHAR(50), pickup_name VARCHAR(100),
    pickup_phone VARCHAR(20), note TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id), product_variant_id INTEGER NOT NULL REFERENCES product_variants(id),
    warranty_period_months INTEGER NOT NULL, product_name VARCHAR(500), quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL, subtotal NUMERIC(12,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS payment_methods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), type VARCHAR(50), provider VARCHAR(100), display_name VARCHAR(150), provider_reference VARCHAR(255), is_default BOOLEAN
);
CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL UNIQUE REFERENCES orders(id),
    payment_method_id INTEGER REFERENCES payment_methods(id), method_type VARCHAR(50) NOT NULL, provider VARCHAR(100), display_name VARCHAR(150),
    amount NUMERIC(12,2) NOT NULL, status VARCHAR(50) NOT NULL, transaction_reference VARCHAR(255), created_at TIMESTAMP, paid_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS promotion_usages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, promotion_id INTEGER REFERENCES promotions(id),
    user_id INTEGER REFERENCES users(id), order_id INTEGER NOT NULL UNIQUE REFERENCES orders(id),
    status VARCHAR(30), discount_amount NUMERIC(12,2), UNIQUE(user_id,promotion_id)
);
CREATE TABLE IF NOT EXISTS warranty_cards (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_item_id INTEGER NOT NULL REFERENCES order_items(id),
    serial_number VARCHAR(100) NOT NULL UNIQUE, start_date TIMESTAMP NOT NULL, end_date TIMESTAMP NOT NULL, status VARCHAR(50)
);
CREATE TABLE IF NOT EXISTS reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_item_id INTEGER NOT NULL REFERENCES order_items(id),
    rating INTEGER NOT NULL, comment TEXT, review_date TIMESTAMP
);
