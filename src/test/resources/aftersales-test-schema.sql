ALTER TABLE order_items ADD COLUMN IF NOT EXISTS pc_custom_id INTEGER;
ALTER TABLE product_variants ADD COLUMN IF NOT EXISTS slug VARCHAR(150);
ALTER TABLE warranty_cards ADD COLUMN IF NOT EXISTS replaces_card_id INTEGER;
CREATE TABLE IF NOT EXISTS service_intakes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intake_code VARCHAR(50) NOT NULL UNIQUE, order_id INTEGER NOT NULL REFERENCES orders(id),
    user_id INTEGER NOT NULL REFERENCES users(id), created_by INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL, returned_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS service_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_code VARCHAR(50) NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id), warranty_card_id INTEGER NOT NULL REFERENCES warranty_cards(id),
    intake_id INTEGER NOT NULL REFERENCES service_intakes(id), issue_description TEXT NOT NULL,
    condition_note TEXT, accessories_note TEXT, contact_name VARCHAR(100), contact_phone VARCHAR(20),
    assigned_technician_id INTEGER, status VARCHAR(50) NOT NULL, resolution VARCHAR(50),
    expected_return_date DATE, technician_note TEXT, public_note TEXT, created_at TIMESTAMP,
    completed_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS service_request_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_request_id INTEGER NOT NULL REFERENCES service_requests(id), actor_id INTEGER NOT NULL REFERENCES users(id),
    event_type VARCHAR(50) NOT NULL, from_status VARCHAR(50), to_status VARCHAR(50) NOT NULL,
    internal_note TEXT, public_note TEXT, created_at TIMESTAMP NOT NULL
);
